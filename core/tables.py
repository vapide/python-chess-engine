BETWEEN = [[0 for _ in range(64)] for _ in range(64)]
LINE = [[0 for _ in range(64)] for _ in range(64)]

def generate_ray_tables():
    directions = [
        (1, 0),    # east
        (-1, 0),   # west
        (0, 1),    # north
        (0, -1),   # south
        (1, 1),
        (-1, -1),
        (1, -1),
        (-1, 1)
    ]

    for start in range(64):
        sf = start % 8
        sr = start // 8
        for df, dr in directions:
            ray = []
            f = sf + df
            r = sr + dr
            while 0 <= f < 8 and 0 <= r < 8:
                ray.append(r * 8 + f)

                f += df
                r += dr
            for end_index, end in enumerate(ray):
                line = 1 << start
                for sq in ray:
                    line |= 1 << sq
                    if sq == end:
                        break
                LINE[start][end] = line

                between = 0

                for sq in ray[:end_index]:
                    between |= 1 << sq

                BETWEEN[start][end] = between

generate_ray_tables()

